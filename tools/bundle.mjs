#!/usr/bin/env node
'use strict';
/* Regenerate ALL-FILES.md - every tracked file verbatim in one document.

   Usage: node tools/bundle.mjs
   The file list comes from `git ls-files`, so the bundle can never drift from the
   repository; ALL-FILES.md itself is excluded. Fences use four backticks because the
   skill files contain triple-backtick blocks. No dependencies (Node >= 18).
*/
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, statSync } from 'node:fs';
import { dirname, extname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SELF = 'ALL-FILES.md';
const LANG = { '.json': 'json', '.md': 'markdown', '.js': 'javascript', '.mjs': 'javascript', '.css': 'css', '.html': 'html', '.yml': 'yaml' };

const files = execFileSync('git', ['ls-files'], { cwd: repoRoot, encoding: 'utf8' })
  .split('\n').map(function (s) { return s.trim(); }).filter(Boolean)
  .filter(function (f) { return f !== SELF; })
  .sort();

const out = [
  '# reasoning-suite - every file, verbatim',
  '',
  'Generated by `node tools/bundle.mjs` from `git ls-files`. Nothing is truncated.',
  'Fences use four backticks because the skill files contain triple-backtick blocks.',
  ''
];
let total = 0;
for (const file of files) {
  const body = readFileSync(resolve(repoRoot, file), 'utf8');
  total += Buffer.byteLength(body);
  out.push('## `' + file + '`', '', '````' + (LANG[extname(file)] || 'text'), body.replace(/\n$/, ''), '````', '');
}
out.push('## File inventory', '', '| path | bytes |', '|---|---|');
for (const file of files) out.push('| `' + file + '` | ' + statSync(resolve(repoRoot, file)).size + ' |');
out.push('| **total** | **' + total + '** |');

writeFileSync(resolve(repoRoot, SELF), out.join('\n') + '\n');
console.log('wrote ' + SELF + ': ' + files.length + ' files, ' + total + ' bytes');
